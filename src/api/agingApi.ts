import { apiClient } from './client';
import { AgingFilterParams, AgingReport } from '@/types/aging.types';

function buildAgingQuery(params?: AgingFilterParams): string {
  const query = new URLSearchParams();
  if (params?.asOfDate) {
    query.append('asOfDate', params.asOfDate);
  }
  if (params?.nonIataId !== undefined && params.nonIataId !== null) {
    query.append('nonIataId', params.nonIataId.toString());
  }
  if (params?.search && params.search.trim()) {
    query.append('search', params.search.trim());
  }
  if (params?.status) {
    query.append('status', params.status);
  }
  return query.toString();
}

/**
 * Retrieves the authoritative Accounts Receivable aging report from the backend engine.
 */
export async function getAgingReport(params?: AgingFilterParams): Promise<AgingReport> {
  const qs = buildAgingQuery(params);
  const endpoint = qs ? `/aging?${qs}` : '/aging';
  return apiClient.get<AgingReport>(endpoint);
}

/**
 * Exports the Accounts Receivable aging report to Excel format generated by the backend.
 */
export async function exportAgingExcel(
  params?: AgingFilterParams
): Promise<{ blob: Blob; filename?: string }> {
  const qs = buildAgingQuery(params);
  const endpoint = qs ? `/aging/export/excel?${qs}` : '/aging/export/excel';
  return apiClient.getBlob(endpoint);
}

/**
 * Exports the Accounts Receivable aging report to PDF format generated by the backend.
 */
export async function exportAgingPdf(
  params?: AgingFilterParams
): Promise<{ blob: Blob; filename?: string }> {
  const qs = buildAgingQuery(params);
  const endpoint = qs ? `/aging/export/pdf?${qs}` : '/aging/export/pdf';
  return apiClient.getBlob(endpoint);
}
